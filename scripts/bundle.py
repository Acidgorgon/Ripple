#!/usr/bin/env python3
"""Bundle the Ripple compiler into one Luau file for `lune build`.

    python3 scripts/bundle.py [out]   (default: build/ripple.luau)

Inlines src/Codec, Parser, Generator and the runtime templates, then appends src/init.luau with its
@self/ requires pointed at the inlined modules."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "ripple.luau")


def read(*p):
    with open(os.path.join(SRC, *p), encoding="utf-8") as f:
        return f.read()


def long_string(s):
    level = 0
    while f"]{'=' * level}]" in s:
        level += 1
    eq = "=" * level
    # a leading newline right after [[ is dropped by Luau, so add one to keep the text exact
    return f"[{eq}[\n{s}]{eq}]"


def strip_strict(s):
    return re.sub(r"^--!strict[^\n]*\n", "", s)


modules = {"Codec": read("Codec.luau"), "Parser": read("Parser.luau"), "Generator": read("Generator.luau")}
parts = ["--!nocheck", "-- Generated by scripts/bundle.py. Do not edit; edit src/ instead.", "local __MOD, __LOADED = {}, {}",
         "local function __require(name)",
         "\tlocal v = __LOADED[name]",
         "\tif v == nil then v = __MOD[name]() __LOADED[name] = v end",
         "\treturn v",
         "end"]
for name, body in modules.items():
    body = strip_strict(body)
    body = re.sub(r'require\("\./(\w+)"\)', r'__require("\1")', body)
    parts.append(f"__MOD[{name!r}] = function()\n{body}\nend")
parts.append("_G.RIPPLE_RUNTIME = {")
for name in ("Server.luau", "Client.luau"):
    parts.append(f"\t[{name!r}] = {long_string(read('runtime', name))},")
parts.append("}")
init = strip_strict(read("init.luau"))
init = re.sub(r'require\("@self/(\w+)"\)', r'__require("\1")', init)
parts.append(init)

os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(parts) + "\n")
print(f"wrote {out}")
